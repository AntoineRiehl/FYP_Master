# ------------------------------------------------------------

K_NEIGHBORS = 15


# ------------------------------------------------------------
# Reproducibility
# ------------------------------------------------------------

RANDOM_STATE = 42


# ------------------------------------------------------------
# Candidate REVIEW shares
#
# 0.00 = original TF-IDF only
# 1.00 = full Yelp reviews only
# ------------------------------------------------------------

REVIEW_SHARES = [

    0.00,

    0.20,

    0.35,

    0.50,

    0.65,

    0.80,

    1.00,

]


